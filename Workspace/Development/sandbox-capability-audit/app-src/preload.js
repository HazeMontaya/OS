
const { contextBridge, ipcRenderer } = require("electron");
contextBridge.exposeInMainWorld("osAPI",{
  status:()=>ipcRenderer.invoke("status:get"),
  getSettings:()=>ipcRenderer.invoke("settings:get"),
  saveSettings:s=>ipcRenderer.invoke("settings:save",s),
  tree:rel=>ipcRenderer.invoke("tree:list",rel),
  readFile:p=>ipcRenderer.invoke("file:read",p),
  writeFile:(path,content,confirmed=false)=>ipcRenderer.invoke("file:write",{path,content,confirmed}),
  createFile:(dir,name,content="",confirmed=false)=>ipcRenderer.invoke("file:create",{dir,name,content,confirmed}),
  deleteFile:(path,confirmed=false)=>ipcRenderer.invoke("file:delete",{path,confirmed}),
  search:q=>ipcRenderer.invoke("search:text",q),
  runEngine:(engine,prompt,options={})=>ipcRenderer.invoke("engine:run",{engine,prompt,options}),
  listModels:()=>ipcRenderer.invoke("models:list"),
  pullModel:m=>ipcRenderer.invoke("models:pull",m),
  snapshot:()=>ipcRenderer.invoke("snapshot:create"),
  selfReview:e=>ipcRenderer.invoke("improve:review",e),
  listAutomations:()=>ipcRenderer.invoke("automations:list"),
  saveAutomations:a=>ipcRenderer.invoke("automations:save",a),
  runAutomation:id=>ipcRenderer.invoke("automations:run",id),
  openPath:p=>ipcRenderer.invoke("shell:openPath",p),
  openExternal:u=>ipcRenderer.invoke("shell:external",u),
  command:(command,confirmed=false)=>ipcRenderer.invoke("shell:command",{command,confirmed}),
  activity:()=>ipcRenderer.invoke("activity:get"),
  devList:()=>ipcRenderer.invoke("dev:list"),
  devCreate:x=>ipcRenderer.invoke("dev:create",x),
  devGet:id=>ipcRenderer.invoke("dev:get",id),
  devPlan:id=>ipcRenderer.invoke("dev:plan",id),
  devBuild:id=>ipcRenderer.invoke("dev:build",id),
  devTest:id=>ipcRenderer.invoke("dev:test",id),
  devReview:id=>ipcRenderer.invoke("dev:review",id),
  devCandidate:id=>ipcRenderer.invoke("dev:candidate",id),
  devLaunchCandidate:id=>ipcRenderer.invoke("dev:launchCandidate",id),
  devPromote:(id,force=false)=>ipcRenderer.invoke("dev:promote",{id,force}),
  devRollback:id=>ipcRenderer.invoke("dev:rollback",id),
  devCleanup:id=>ipcRenderer.invoke("dev:cleanup",id),
  devAutoEvolve:(input={})=>ipcRenderer.invoke("dev:autoEvolve",input),
  capsProbe:()=>ipcRenderer.invoke("caps:probe"),
  capsAudit:()=>ipcRenderer.invoke("caps:audit"),
  capsPlan:(goal,engine="auto")=>ipcRenderer.invoke("caps:plan",{goal,engine}),
  capsInspect:id=>ipcRenderer.invoke("caps:inspect",id),
  capsAdapter:(id,engine="auto")=>ipcRenderer.invoke("caps:adapter",{id,engine}),
  capsInstall:req=>ipcRenderer.invoke("caps:install",req),
  capsAutoAcquire:(goal,engine="auto")=>ipcRenderer.invoke("caps:autoAcquire",{goal,engine}),
  adminStatus:()=>ipcRenderer.invoke("admin:status"),
  adminRelaunch:()=>ipcRenderer.invoke("admin:relaunch"),
  referenceInfo:()=>ipcRenderer.invoke("reference:info"),
  referenceCompare:(engine="auto")=>ipcRenderer.invoke("reference:compare",engine)
});
